def group_by_province() -> dict:
    result: dict = {}
    for c in ALL_CITIES:
        result.setdefault(c["province"], []).append(c)
    return result


def search_cities(keyword: str) -> list:
    if not keyword:
        return []
    kw = keyword.lower().strip()
    matched = [
        c for c in ALL_CITIES
        if kw in c["city_name"] or kw in c["pinyin"] or c["pinyin"].startswith(kw)
    ]
    matched.sort(key=lambda c: c["level"])
    return matched
